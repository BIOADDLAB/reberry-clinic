def main() -> None:
    categories, sections, items = [], [], []

    for category_sort, (category_id, category_label, note, cards) in enumerate(BOARD):
        categories.append(
            {
                "docId": category_id,
                "label": category_label,
                "note": note,
                "sort": category_sort,
                "isPublished": True,
                "seedVersion": VERSION,
            }
        )

        for section_sort, (slug, card_label, card_rows) in enumerate(cards):
            section_id = f"{category_id}--{slug}"
            sections.append(
                {
                    "docId": section_id,
                    "categoryId": category_id,
                    "label": card_label,
                    "sort": section_sort,
                    "isPublished": True,
                    "seedVersion": VERSION,
                }
            )

            for item_sort, (name, sessions) in enumerate(card_rows):
                items.append(
                    {
                        "docId": f"{section_id}--{item_sort:02d}",
                        "categoryId": category_id,
                        "sectionId": section_id,
                        "name": name,
                        "productLabel": "",
                        "description": "",
                        "sessions": [
                            {"id": f"option-{index}", "label": label, "price": price}
                            for index, (label, price) in enumerate(sessions)
                        ],
                        "sort": item_sort,
                        "isPublished": True,
                        "seedVersion": VERSION,
                    }
                )

    payload = {
        "version": VERSION,
        "source": "리베리_수가표_미팅반영.numbers (04_원본 데이터) + 2026-09-03 카톡 피드백",
        "categories": categories,
        "sections": sections,
        "items": items,
    }
    SEED.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")

    prices = sum(len(item["sessions"]) for item in items)
    print(f"categories={len(categories)} cards={len(sections)} items={len(items)} prices={prices}")
    for category in categories:
        cards = [section for section in sections if section["categoryId"] == category["docId"]]
        print(f"  {category['label']}: 카드 {len(cards)}장")


if __name__ == "__main__":
    main()

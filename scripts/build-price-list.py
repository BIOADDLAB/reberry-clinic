def spread(labels: tuple[str, ...], columns: tuple[tuple[str, tuple[int, ...]], ...]) -> list:
    """열마다 적어 둔 가격을 줄(제품·등급)별로 뒤집는다.

    엑셀이 "용량 한 줄 · 제품 세 칸" 으로 적혀 있어서, 옮겨 적을 때 눈으로 대조할 수 있게
    여기서도 (열 이름, 제품 순 가격) 모양으로 두고 뒤집는 일만 코드가 한다.
    """
    return [
        (label, [(column, prices[index]) for column, prices in columns])
        for index, label in enumerate(labels)
    ]


def toxin(*columns: tuple[str, tuple[int, ...]]) -> list[tuple[str, list[tuple[str, int]]]]:
    """보톡스 — 줄은 제품(하이톡스·코어톡스·제오민), 열은 부위·용량."""
    return spread(BOTOX, columns)


def grades(*columns: tuple[str, tuple[int, ...]]) -> list[tuple[str, list[tuple[str, int]]]]:
    """필러 — 줄은 등급(국산·국산 프리미엄·수입), 열은 용량."""
    return spread(FILLER_GRADES, columns)


def brands(*prices: int) -> list[tuple[str, list[tuple[str, int]]]]:
    """열이 하나뿐인 카드 — 용량은 카드 제목에 있으니 줄은 제품 이름만 쓴다."""
    return [(product, [("1회", price)]) for product, price in zip(BOTOX, prices)]


def rows(*entries: tuple[str, list[tuple[str, int]]]) -> list:
    return list(entries)


def one(name: str, price: int, unit: str = "1회") -> tuple[str, list[tuple[str, int]]]:
    return (name, [(unit, price)])


def many(name: str, *sessions: tuple[str, int]) -> tuple[str, list[tuple[str, int]]]:
    return (name, list(sessions))



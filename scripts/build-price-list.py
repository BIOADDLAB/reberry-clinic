def botox(option: str, *prices: int) -> list[tuple[str, list[tuple[str, int]]]]:
    """용량 선택지가 여러 개인 카드용 — 줄 이름에 용량과 제품을 같이 쓴다."""
    return [(f"{option} · {product}", [("1회", price)]) for product, price in zip(BOTOX, prices)]


def brands(*prices: int) -> list[tuple[str, list[tuple[str, int]]]]:
    """카드 제목이 이미 시술·용량을 말하는 경우 — 줄은 제품 이름만 쓴다."""
    return [(product, [("1회", price)]) for product, price in zip(BOTOX, prices)]


def rows(*entries: tuple[str, list[tuple[str, int]]]) -> list:
    return list(entries)


def one(name: str, price: int, unit: str = "1회") -> tuple[str, list[tuple[str, int]]]:
    return (name, [(unit, price)])


def many(name: str, *sessions: tuple[str, int]) -> tuple[str, list[tuple[str, int]]]:
    return (name, list(sessions))


